import assert from 'node:assert/strict';
import test from 'node:test';
import { createWriteEvidence } from '../agent-results.js';
import { boundTmuxToolEvidence, encodeTmuxFrame, parseTmuxRequest, parseTmuxResponse, TmuxFrameDecoder, TmuxWorkerLedger, TMUX_TEXT_BYTES, TMUX_FRAME_BYTES } from '../tmux-protocol.js';

test('exact settled job carries bounded native write observations and telemetry, never inferred completeness', () => {
  const identity = { workerId: 'w', sessionId: 's', generation: 'g', ownerNonce: 'a'.repeat(64), epoch: 0 };
  const job = { ...identity, jobId: 'j', runId: 'r', taskId: 't', source: 'coordinator' as const };
  const ledger = new TmuxWorkerLedger(identity);
  const prompt = parseTmuxRequest({ version: 1, requestId: 'p', identity, action: 'prompt', expectedJobId: null, job, text: 'synthetic edit' });
  ledger.accept(prompt);
  const writes = createWriteEvidence('/srv/devops/fixture', undefined);
  writes.event({ type: 'tool_execution_start', toolName: 'edit', toolCallId: 'e1', args: { path: 'src/a.ts' } });
  writes.event({ type: 'tool_execution_end', toolName: 'edit', toolCallId: 'e1', isError: false });
  writes.event({ type: 'tool_execution_start', toolName: 'write', toolCallId: 'e2', args: { path: '../outside.ts' } });
  writes.event({ type: 'tool_execution_end', toolName: 'write', toolCallId: 'e2', isError: false });
  writes.event({ type: 'tool_execution_start', toolName: 'write', toolCallId: 'e3', args: { path: 'failed.ts' } });
  writes.event({ type: 'tool_execution_end', toolName: 'write', toolCallId: 'e3', isError: true });
  writes.event({ type: 'tool_execution_start', toolName: 'bash', toolCallId: 'e4', args: {} });
  const evidence = boundTmuxToolEvidence(writes.snapshot());
  assert.deepEqual(evidence.files_changed, ['../outside.ts', 'src/a.ts']);
  assert.equal(evidence.evidence_complete, false);
  assert.ok(evidence.evidence_reasons.includes('Bash/MCP/other tools are not attributed.'));
  const telemetry = { tokens: { input: 10, output: 4, cache_read: 2, cache_write: null }, context_percent: 12.5, elapsed_seconds: 3 };
  const staleJob = process.env.CLANKERS_TMUX_EVIDENCE_PLANTED_FAULT === '1' ? job : { ...job, taskId: 'other-task' };
  assert.throws(() => ledger.settle(staleJob, 'completed', 'wrong', false, { telemetry, toolEvidence: evidence }), /Stale/);
  ledger.settle(job, 'completed', '\u0000'.repeat(TMUX_TEXT_BYTES), false, { telemetry, toolEvidence: evidence });
  const show = parseTmuxRequest({ version: 1, requestId: 'show', identity, action: 'show', expectedJobId: 'j', job: null, text: null });
  const reply = ledger.accept(show);
  const frame = encodeTmuxFrame(reply);
  assert.ok(frame.length <= TMUX_FRAME_BYTES);
  const result = parseTmuxResponse(new TmuxFrameDecoder().push(frame)[0], show).snapshot.result!;
  assert.deepEqual(result.telemetry, telemetry);
  assert.deepEqual(result.toolEvidence, evidence);
  telemetry.tokens.input = 999;
  assert.equal(result.telemetry?.tokens.input, 10);
  assert.ok(Object.isFrozen(result.telemetry?.tokens));
  assert.throws(() => parseTmuxResponse({ ...reply, snapshot: { ...reply.snapshot, result: { ...result, telemetry: { ...result.telemetry, elapsed_seconds: -1 } } } }, show), /telemetry/);
  assert.throws(() => parseTmuxResponse({ ...reply, snapshot: { ...reply.snapshot, result: { ...result, toolEvidence: { ...evidence, evidence_complete: true } } } }, show), /evidence/);
  const bounded = boundTmuxToolEvidence({ files_changed: Array.from({ length: 256 }, (_, i) => `${i}-` + '\u0000'.repeat(4000)), evidence_complete: false, evidence_reasons: ['Tool-event observations only.'] });
  assert.ok(Buffer.byteLength(JSON.stringify(bounded)) <= 16384);
  assert.ok(bounded.evidence_reasons.includes('Transport omitted observed paths.'));
  assert.equal(bounded.evidence_complete, false);
  const second = { ...job, jobId: 'j2', runId: 'r2', taskId: 't2' };
  ledger.accept(parseTmuxRequest({ ...prompt, requestId: 'p2', job: second }));
  ledger.settle(second, 'completed', 'second', false);
  assert.equal(ledger.snapshot('j2').result?.telemetry, null);
  assert.equal(ledger.snapshot('j2').result?.toolEvidence, 'unavailable');
  assert.deepEqual(ledger.snapshot('j').result?.toolEvidence, evidence);
});
